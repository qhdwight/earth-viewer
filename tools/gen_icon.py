"""Converts the app logo into small PNG icons embedded in src/icon.h.

Usage: python tools/gen_icon.py assets/logo.png src/icon.h

Needs Pillow. The window and taskbar never show the icon larger than 64
pixels, so the 512 pixel logo is downscaled to the sizes the app uses rather
than embedded whole. At startup main.cc turns the PNG bytes into icons with
CreateIconFromResourceEx, so no resource compiler is involved.
"""

import io
import sys

from PIL import Image

SIZES = (32, 64)
BYTES_PER_LINE = 20


def main(src, dst):
    logo = Image.open(src).convert("RGBA")
    lines = [
        "// Generated by tools/gen_icon.py from assets/logo.png. Do not edit by hand.",
        "#pragma once",
        "",
        '#include "src/core.h"',
        "",
        "// PNG files, smallest first; main.cc picks one per icon size.",
    ]
    for size in SIZES:
        buffer = io.BytesIO()
        logo.resize((size, size), Image.LANCZOS).save(buffer, format="PNG", optimize=True)
        data = buffer.getvalue()
        lines.append(f"inline constexpr U8 kIconPng{size}[{len(data)}] = {{")
        for i in range(0, len(data), BYTES_PER_LINE):
            lines.append("    " + " ".join(f"{b}," for b in data[i:i + BYTES_PER_LINE]))
        lines.append("};")
        lines.append("")
        print(f"{size}x{size}: {len(data)} bytes")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
