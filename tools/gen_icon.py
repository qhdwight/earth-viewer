"""Converts the app logo into small PNG icons embedded in src/icon.hpp.

Usage: python tools/gen_icon.py assets/logo.png src/icon.hpp

Needs Pillow. The logo is downscaled to the sizes the app uses rather than
embedded whole. On Windows the window and taskbar never show the icon larger
than 64 pixels, and platform_win32.hpp turns those PNG bytes into icons with
CreateIconFromResourceEx, so no resource compiler is involved. The macOS Dock
shows it at up to 256 points, 512 pixels on a Retina display, so
platform_macos.mm uses the 512 pixel one. X11 takes window icons as raw pixels
rather than PNG, so platform_linux.hpp uses a 64 pixel ARGB copy. Each build only
links the sizes it references.
"""

import io
import sys

from PIL import Image

SIZES = (32, 64, 512)
ARGB_SIZE = 64
BYTES_PER_LINE = 20
PIXELS_PER_LINE = 8


def main(src, dst):
    logo = Image.open(src).convert("RGBA")
    lines = [
        "// Generated by tools/gen_icon.py from assets/logo.png. Do not edit by hand.",
        "#pragma once",
        "",
        '#include "src/core.hpp"',
        "",
        "// PNG files, smallest first; the platform layer picks one per icon size.",
    ]
    for size in SIZES:
        buffer = io.BytesIO()
        logo.resize((size, size), Image.LANCZOS).save(buffer, format="PNG", optimize=True)
        data = buffer.getvalue()
        lines.append(f"inline constexpr U8 kIconPng{size}[{len(data)}] = {{")
        for i in range(0, len(data), BYTES_PER_LINE):
            lines.append("    " + " ".join(f"{b}," for b in data[i:i + BYTES_PER_LINE]))
        lines.append("};")
        lines.append("")
        print(f"{size}x{size}: {len(data)} bytes")
    rgba = logo.resize((ARGB_SIZE, ARGB_SIZE), Image.LANCZOS).tobytes()
    pixels = [
        rgba[i + 3] << 24 | rgba[i] << 16 | rgba[i + 1] << 8 | rgba[i + 2]
        for i in range(0, len(rgba), 4)
    ]
    lines.append("// Unpremultiplied 0xAARRGGBB pixels, rows top to bottom.")
    lines.append(f"inline constexpr U32 kIconArgbSize = {ARGB_SIZE};")
    lines.append(f"inline constexpr U32 kIconArgb{ARGB_SIZE}[{len(pixels)}] = {{")
    for i in range(0, len(pixels), PIXELS_PER_LINE):
        lines.append("    " + " ".join(f"0x{p:08X}," for p in pixels[i:i + PIXELS_PER_LINE]))
    lines.append("};")
    lines.append("")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
