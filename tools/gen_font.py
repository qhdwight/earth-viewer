"""Converts printable ASCII from a TrueType font into src/font.hpp.

Usage: python tools/gen_font.py Inconsolata.ttf src/font.hpp

Needs fontTools. The font is Inconsolata 3.001 by the Inconsolata Project
Authors, under the SIL Open Font License 1.1 (see src/LICENSE-FONT):
https://raw.githubusercontent.com/google/fonts/main/ofl/inconsolata/Inconsolata%5Bwdth%2Cwght%5D.ttf

It is a variable font; its glyf table holds the default instance, Regular.
Each glyph becomes contours of quadratic curves, the input slug.hpp builds the
Slug curve and band data from at startup. TrueType's runs of off-curve points
are split into single curves at their implied midpoints, composite glyphs are
flattened, and every contour is closed. Coordinates are in half font units,
because the implied midpoints can fall on half units, so they stay exact.
"""

import sys

from fontTools.pens.basePen import decomposeQuadraticSegment
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont

FIRST_CHARACTER = 32
CHARACTER_COUNT = 95  # printable ASCII
ITEMS_PER_LINE = 8


def half_units(point):
    """A point in font units as integers in half font units, exactly."""
    x, y = point[0] * 2, point[1] * 2
    assert x == int(x) and y == int(y), point
    assert -32768 <= x <= 32767 and -32768 <= y <= 32767, point
    return int(x), int(y)


def main(src, dst):
    font = TTFont(src)
    units_per_em = font["head"].unitsPerEm
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()

    advances = []        # font units, per glyph
    glyph_contours = []  # first contour of each glyph, plus a final end
    contour_starts = []  # half units
    contour_curves = []  # first curve of each contour, plus a final end
    curves = []          # control x, y, end x, y in half units

    for code in range(FIRST_CHARACTER, FIRST_CHARACTER + CHARACTER_COUNT):
        name = cmap[code]
        pen = DecomposingRecordingPen(glyph_set)
        glyph_set[name].draw(pen)
        glyph_contours.append(len(contour_starts))
        start = current = None
        for operator, arguments in pen.value:
            if operator == "moveTo":
                start = current = arguments[0]
                contour_starts.append(half_units(start))
                contour_curves.append(len(curves))
            elif operator == "lineTo":
                # A straight line repeats its end point as the control point,
                # the encoding the Slug reference recommends.
                current = arguments[0]
                curves.append(half_units(current) + half_units(current))
            elif operator == "qCurveTo":
                assert arguments[-1] is not None, f"contour without on-curve points in {name!r}"
                for control, end in decomposeQuadraticSegment(arguments):
                    curves.append(half_units(control) + half_units(end))
                    current = end
            elif operator in ("closePath", "endPath"):
                if current != start:
                    curves.append(half_units(start) + half_units(start))
            else:
                raise ValueError(f"unsupported outline operator {operator} in {name!r}")
        advances.append(font["hmtx"][name][0])
    glyph_contours.append(len(contour_starts))
    contour_curves.append(len(curves))

    def array(declaration, items, width):
        out = [f"inline constexpr {declaration} = {{"]
        for i in range(0, len(items), width):
            out.append("    " + " ".join(items[i:i + width]))
        out.append("};")
        return out

    pairs = [f"{{{x}, {y}}}," for x, y in contour_starts]
    quads = [f"{{{a}, {b}, {c}, {d}}}," for a, b, c, d in curves]
    lines = [
        "// Generated by tools/gen_font.py from Inconsolata 3.001. Do not edit by hand.",
        "// Copyright 2006 The Inconsolata Project Authors; SIL Open Font License 1.1, see src/LICENSE-FONT.",
        "#pragma once",
        "",
        '#include "src/core.hpp"',
        "",
        "// Printable ASCII outlines as quadratic curves, baseline at y = 0, y up.",
        "// Coordinates are in half font units.",
        f"inline constexpr F32 kFontHalfUnitsPerEm = {2 * units_per_em}.0f;",
        f"inline constexpr U32 kFontFirstCharacter = {FIRST_CHARACTER};",
        f"inline constexpr U32 kFontGlyphCount = {CHARACTER_COUNT};",
        f"inline constexpr U32 kFontContourCount = {len(contour_starts)};",
        f"inline constexpr U32 kFontCurveCount = {len(curves)};",
        "// From the top of the line to the baseline, in half font units.",
        f"inline constexpr I32 kFontAscent = {2 * font['hhea'].ascent};",
        "",
        "// Advance width of each glyph, in half font units.",
        *array("I16 kFontAdvances[kFontGlyphCount]", [f"{2 * a}," for a in advances], 16),
        "",
        "// Glyph i owns contours kFontGlyphContours[i] up to kFontGlyphContours[i + 1].",
        *array("U16 kFontGlyphContours[kFontGlyphCount + 1]", [f"{c}," for c in glyph_contours], 16),
        "",
        "// Contour i starts at kFontContourStarts[i] and owns curves",
        "// kFontContourCurves[i] up to kFontContourCurves[i + 1]. Contours are closed:",
        "// the last curve ends at the start.",
        *array("I16 kFontContourStarts[kFontContourCount][2]", pairs, ITEMS_PER_LINE),
        "",
        *array("U16 kFontContourCurves[kFontContourCount + 1]", [f"{c}," for c in contour_curves], 16),
        "",
        "// Each curve runs from the end of the previous one, or the contour start,",
        "// through the control point to the end point: control x, y, end x, y. A",
        "// straight line repeats its end point as the control point.",
        *array("I16 kFontCurves[kFontCurveCount][4]", quads, ITEMS_PER_LINE // 2),
        "",
    ]
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{CHARACTER_COUNT} glyphs, {len(contour_starts)} contours, {len(curves)} curves -> {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
