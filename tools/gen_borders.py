"""Converts Natural Earth country polygons and state boundary lines (GeoJSON)
into src/borders.h.

Usage: python tools/gen_borders.py <ne_50m_admin_0_countries.geojson>            <ne_50m_admin_1_states_provinces_lines.geojson> src/borders.h

Source data (public domain):
https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson
https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_1_states_provinces_lines.geojson

Every country polygon ring becomes a closed polyline, and every internal state
boundary of the countries in STATE_COUNTRIES an open one. Points are
(longitude, latitude) pairs quantized to 1/180 degree so each coordinate fits
in an int16.
"""

import json
import sys

UNITS_PER_DEGREE = 180
PAIRS_PER_LINE = 8
# ISO 3166 alpha-3 codes of countries whose internal state boundaries are drawn.
STATE_COUNTRIES = {"USA"}


def quantize(coordinates):
    points = []
    for lon, lat in coordinates:
        point = (round(lon * UNITS_PER_DEGREE), round(lat * UNITS_PER_DEGREE))
        if not points or points[-1] != point:
            points.append(point)
    return points


def main(countries_src, states_src, dst):
    with open(countries_src, encoding="utf-8") as f:
        data = json.load(f)

    rings = []  # list of lists of (lon, lat) int pairs
    for feature in data["features"]:
        geometry = feature["geometry"]
        polygons = geometry["coordinates"]
        if geometry["type"] == "Polygon":
            polygons = [polygons]
        for polygon in polygons:
            for ring in polygon:
                points = quantize(ring)
                if len(points) >= 2:
                    rings.append(points)
    country_ring_count = len(rings)

    with open(states_src, encoding="utf-8") as f:
        states = json.load(f)
    for feature in states["features"]:
        if feature["properties"]["ADM0_A3"] not in STATE_COUNTRIES:
            continue
        geometry = feature["geometry"]
        parts = geometry["coordinates"]
        if geometry["type"] == "LineString":
            parts = [parts]
        for part in parts:
            points = quantize(part)
            if len(points) >= 2:
                rings.append(points)

    point_count = sum(len(r) for r in rings)
    lines = [
        "// Generated by tools/gen_borders.py from Natural Earth 1:50m admin 0",
        "// countries and admin 1 state boundary lines (public domain). Do not",
        "// edit by hand.",
        "#pragma once",
        "",
        '#include "src/core.h"',
        "",
        "// Longitude and latitude are stored in units of 1/180 degree.",
        f"inline constexpr I32 kBorderUnitsPerDegree = {UNITS_PER_DEGREE};",
        f"inline constexpr U32 kBorderRingCount = {len(rings)};",
        f"inline constexpr U32 kBorderPointCount = {point_count};",
        f"inline constexpr U32 kBorderCountryRingCount = {country_ring_count};",
        "",
        "// A ring is a polyline. Country outlines come first and are closed: their",
        "// last point equals their first. State boundaries follow and are open.",
        "struct BorderRing {",
        "    U32 first;",
        "    U32 count;",
        "};",
        "",
        "inline constexpr BorderRing kBorderRings[kBorderRingCount] = {",
    ]
    first = 0
    for ring in rings:
        lines.append(f"    {{{first}, {len(ring)}}},")
        first += len(ring)
    lines += [
        "};",
        "",
        "// {longitude, latitude} pairs, rings laid out back to back.",
        "inline constexpr I16 kBorderPoints[kBorderPointCount][2] = {",
    ]
    for ring in rings:
        for i in range(0, len(ring), PAIRS_PER_LINE):
            chunk = ring[i:i + PAIRS_PER_LINE]
            lines.append("    " + " ".join(f"{{{lon}, {lat}}}," for lon, lat in chunk))
    lines += ["};", ""]

    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{country_ring_count} country rings, {len(rings) - country_ring_count} state lines, "
          f"{point_count} points -> {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3])
